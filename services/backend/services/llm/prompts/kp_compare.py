_OUTLINE_SYSTEM = """\
Ты размечаешь коммерческое предложение (КП) поставщика на разделы. Тебе дают \
фрагмент текста КП; страницы отмечены строками «--- Страница N ---».

Найди во фрагменте все места, где НАЧИНАЕТСЯ новый раздел или новая позиция \
предложения: позиция оборудования (Item, поз., пункт спецификации), работы и \
услуги (монтаж, пусконаладка, обучение, проектирование), гарантия, \
коммерческие условия, перечень того, что НЕ входит в поставку, перечень \
отклонений от ТЗ, общее описание поставки, сводная таблица или оглавление.

Для каждого начала верни:
- anchor — строка заголовка ДОСЛОВНО как в тексте (одна строка, до 120 \
символов), чтобы её можно было найти поиском;
- position — номер позиции, как он написан в КП («Item 6», «1.5», «Поз. 3»), \
или null;
- title — короткое название раздела на языке КП;
- title_ru — то же по-русски;
- kind — один из:
  equipment — оборудование, узел, комплектующие, опции к оборудованию;
  service — работы и услуги;
  summary — оглавление, сводная таблица позиций и цен;
  scope — общее описание поставки, состав линии, исходные данные, продукция;
  exclusions — что НЕ входит в поставку, границы поставки;
  deviations — отклонения от ТЗ или тендерной документации;
  commercial — цены, оплата, сроки и условия поставки, гарантийные условия;
  other — прочее (презентация компании, реквизиты, перечень брендов).

Правила:
1. anchor должен дословно встречаться во фрагменте; ничего не придумывай.
2. Строки внутри оглавления или сводной таблицы — не начала позиций: отметь \
только начало самой таблицы (kind = summary).
3. Если позиция обозначена двумя строками подряд («Item 6», затем строка с \
названием), anchor — первая из них, title — название.
4. Колонтитулы, номера страниц и реквизиты, повторяющиеся на каждой \
странице, — не разделы.
5. Внутренние подзаголовки позиции (APPLICATION, TECHNICAL DATA, \
CONSTRUCTION, Характеристики и т. п.) — не новые разделы.
6. Если во фрагменте новых разделов нет, верни пустой список.

Верни ТОЛЬКО JSON:
{"sections": [{"anchor": "Item 6", "position": "Item 6", \
"title": "CURD / WHEY ROTARY LOBE PUMP", \
"title_ru": "Роторно-лопастной насос для сгустка/сыворотки", \
"kind": "equipment"}]}"""


def build_outline_prompt(
    chunk: str, *, chunk_no: int, total: int
) -> tuple[str, str]:
    """Find where the sections of the offer start in one fragment."""
    user = f"Фрагмент {chunk_no} из {total}.\n\n### Текст КП:\n{chunk}"
    return _OUTLINE_SYSTEM, user


_OBJECTS_SYSTEM = """\
Ты разбираешь структуру технического задания (ТЗ) на поставку. Тебе дают \
список разделов ТЗ: ключ в квадратных скобках, номер в документе, текст \
раздела и число конечных пунктов под ним.

Отметь разделы, каждый из которых описывает ОДИН объект для сравнения с \
коммерческим предложением:
- equipment — единица оборудования, установка, машина, система, ёмкость, \
транспортёр, узел, который поставщик описывает отдельно;
- general — блок общих требований: ко всему оборудованию сразу, работы и \
услуги, документация, гарантия, сроки, обязательства участника, исходные \
данные о продукте и сырье.

Правила:
1. Выбирай самый узкий раздел, который ещё описывает объект целиком. Если в \
разделе несколько единиц оборудования (например, сыроизготовитель и его \
буферная ёмкость), отметь каждую единицу, а общий раздел не отмечай.
2. Не отмечай разделы-группы параметров («Обработка поверхностей:», \
«Материал:», «Комплектация:») — они часть своего объекта.
3. Пункт относится к ближайшему отмеченному разделу над ним; пункты вне \
отмеченных разделов попадут в общий блок — это нормально.
4. key — ключ раздела из квадратных скобок, без изменений.
5. title_ru — короткое название объекта, как в ТЗ.

Верни ТОЛЬКО JSON:
{"objects": [{"key": "22.1", "kind": "equipment", \
"title_ru": "Сыроизготовитель"}]}"""


def build_objects_prompt(outline: str) -> tuple[str, str]:
    """Mark the TZ sections that each describe one object to compare."""
    return _OBJECTS_SYSTEM, f"### Разделы ТЗ:\n{outline}"


_ALIGN_RULES = """\
Правила:
1. Сопоставляй по назначению и смыслу, а не по совпадению слов: КП может быть \
на другом языке и называть оборудование иначе (cheese vat — сыроизготовитель).
2. Объект ТЗ может описываться в нескольких разделах КП (основная машина, её \
узлы, опции, площадки обслуживания), а раздел КП может относиться к \
нескольким объектам ТЗ.
3. Оборудование того же типа, которое служит ДРУГОМУ объекту, — не тот \
объект: насос станции мойки не относится к насосу сыроизготовителя, если в \
ТЗ это разные объекты.
4. Общим блокам ТЗ (работы, документация, гарантия, сроки, требования ко \
всему оборудованию) соответствуют разделы КП об услугах, коммерческих \
условиях и общем описании поставки.
5. Если подходящего раздела нет — пустой список. Не подбирай «похожее»."""

_ALIGN_FORWARD_SYSTEM = f"""\
Ты сопоставляешь техническое задание (ТЗ) и коммерческое предложение (КП). \
Даны объекты ТЗ (оборудование и блоки требований) и разделы КП. Для КАЖДОГО \
объекта ТЗ укажи разделы КП, в которых поставщик описывает именно этот объект \
или его части.

{_ALIGN_RULES}

Верни ТОЛЬКО JSON:
{{"objects": [{{"object": "O3", "sections": ["S12", "S13"]}}]}}"""

_ALIGN_BACKWARD_SYSTEM = f"""\
Ты сопоставляешь техническое задание (ТЗ) и коммерческое предложение (КП). \
Даны объекты ТЗ (оборудование и блоки требований) и разделы КП. Для КАЖДОГО \
раздела КП укажи объекты ТЗ, которые этот раздел описывает.

{_ALIGN_RULES}

Верни ТОЛЬКО JSON:
{{"sections": [{{"section": "S12", "objects": ["O3"]}}]}}"""


def build_align_prompt(
    objects: str, sections: str, *, backward: bool
) -> tuple[str, str]:
    """Map TZ objects to KP sections (forward) or sections to objects."""
    system = _ALIGN_BACKWARD_SYSTEM if backward else _ALIGN_FORWARD_SYSTEM
    user = f"### Разделы КП:\n{sections}\n\n### Объекты ТЗ:\n{objects}"
    return system, user


_VERDICT_SYSTEM = """\
Ты — эксперт по проверке коммерческих предложений (КП) на соответствие \
техническому заданию (ТЗ). Проверка идёт для отдела закупок, ошибка в любую \
сторону дорого стоит, поэтому опирайся только на данный тебе текст КП.

Тебе дают:
1. Текст КП, разбитый на разделы; каждый раздел начинается строкой \
«[S… | страницы | название]».
2. Разделы КП, которые относятся ко всем пунктам: что не входит в поставку и \
отклонения от ТЗ, — учитывай их для каждого пункта.
3. Проверяемый объект ТЗ и разделы КП, где поставщик описывает этот объект: \
ищи ответ прежде всего в них.
4. Пункты ТЗ этого объекта: R1, R2, … с номером в ТЗ и контекстом. Строка \
«КП о пункте» — место КП, где поставщик сам называет этот пункт ТЗ по номеру \
(обычно перечень отклонений): учитывай её в первую очередь.

Для КАЖДОГО пункта дай вердикт:
- met — КП прямо подтверждает выполнение ВСЕХ условий пункта;
- partial — КП подтверждает часть условий, а остальные не упомянуты, или \
подтверждает с оговоркой («опционально», «по запросу», «будет уточнено \
позже», «по согласованию»);
- missing — КП явно противоречит пункту (другое значение, худшая \
характеристика, меньшее количество, другой тип) ИЛИ нужная поставка или \
работа прямо исключена из предложения или названа отклонением от ТЗ;
- not_found — в КП нет сведений по пункту.

Как сравнивать:
1. Числа: «не менее X» выполнено, если в КП значение ≥ X; «не более X» — если \
≤ X; диапазон — если значение КП внутри него. Отсутствие в КП слов «не \
менее»/«не более» само по себе не делает пункт частичным. Учитывай единицы \
(л и м³, мм и м, бар и МПа, кг/ч и т/сутки).
2. Материал или класс выше требуемого выполняет требование «не хуже» \
(AISI 316 выполняет «не хуже AISI 304»).
3. «Ответственность Участника», «по выбору Участника» — met, если КП называет \
конкретное решение; если КП молчит — not_found.
4. «Участник обязан предоставить/подтвердить …» — met, если КП это содержит \
или прямо подтверждает; иначе not_found. Если пункт описывает то, что \
обеспечивает Организатор (покупатель), а КП тоже относит это к покупателю \
или выводит из своей поставки, — met: стороны согласны. Если КП прямо \
перекладывает на покупателя то, что ТЗ возлагает на Участника, — missing.
5. Если пункт касается того, что поставщик исключил из поставки или назвал \
отклонением, — missing с цитатой этого места. Если исключён весь объект \
(ёмкость, модуль, установка), то missing — КАЖДЫЙ его пункт, даже если \
отдельный параметр в КП не упомянут.
6. Сведения о ДРУГОМ оборудовании не подтверждают пункт: насос станции мойки \
не подтверждает требования к насосу сыроизготовителя. Если в разделах \
объекта ответа нет, но другой раздел КП явно говорит об этом же \
оборудовании или обо всём оборудовании сразу («все двигатели — IP55»), \
используй его.
7. Ничего не додумывай; общие рекламные фразы без конкретики не \
подтверждают пункт.

Доказательство:
- для met, partial и missing дай в evidence 1–3 цитаты: дословный фрагмент \
текста КП на языке КП, без перевода и без изменений, до 300 символов, и \
раздел S…, из которого он взят;
- для not_found evidence — пустой список.

offer_value — что предлагает КП по пункту, кратко по-русски; для not_found — \
null.
explanation — обоснование по-русски, 1–2 предложения: для partial — чего не \
хватает, для missing — в чём противоречие.

Верни ТОЛЬКО JSON, по одной записи на КАЖДЫЙ пункт:
{"results": [{"id": "R1", "status": "met", \
"evidence": [{"section": "S12", "quote": "..."}], \
"offer_value": "...", "explanation": "..."}]}"""


def build_verdict_prompt(
    *,
    offer_text: str,
    shared_sections: str,
    object_title: str,
    object_sections: str,
    requirements: str,
) -> tuple[str, str]:
    """Verdicts for the points of one TZ object.

    *offer_text* comes first: when it is the whole offer it is the same for
    every object, and the provider's cache reuses it from call to call.
    """
    shared = shared_sections or "в КП таких разделов нет"
    scope = object_sections or (
        "не определены — ищи ответ по всему тексту КП, соблюдая правило 6"
    )
    user = (
        f"### Текст КП:\n{offer_text}\n\n"
        "### Разделы КП, которые относятся ко всем пунктам "
        f"(исключения из поставки, отклонения от ТЗ): {shared}\n\n"
        f"### Объект ТЗ: {object_title}\n"
        f"Разделы КП, где описан этот объект: {scope}\n\n"
        f"### Пункты ТЗ:\n{requirements}"
    )
    return _VERDICT_SYSTEM, user


_TERMS_SYSTEM = """\
Ты помогаешь найти в коммерческом предложении (КП) место, где поставщик \
отвечает на пункт технического задания (ТЗ). Для КАЖДОГО пункта дай 3–6 \
коротких поисковых выражений (1–3 слова): ключевые термины на языке КП и \
по-русски, марки и стандарты, характерные числа с единицами.

Не давай общих слов, которые есть почти везде («оборудование», «система», \
«equipment», «stainless steel»).

Верни ТОЛЬКО JSON:
{"terms": [{"id": "R1", "terms": ["submersible pump", "погружной насос", \
"DN 50"]}]}"""


def build_terms_prompt(
    requirements: str, *, kp_language: str
) -> tuple[str, str]:
    """Search terms for points the first pass found nothing about."""
    user = f"Язык КП: {kp_language}.\n\n### Пункты ТЗ:\n{requirements}"
    return _TERMS_SYSTEM, user


_SCOPE_SYSTEM = """\
Ты проверяешь, какие объекты технического задания (ТЗ) поставщик НЕ включил \
в своё коммерческое предложение (КП). Даны текст КП (разделы начинаются \
строкой «[S… | страницы | название]») и список объектов ТЗ.

Для КАЖДОГО объекта определи по тексту КП:
- included — объект (или его аналог под другим названием) входит в \
предложение;
- excluded — КП прямо говорит, что сам объект не поставляется: «not \
included», «not in scope», «out of scope», «не входит в поставку», «исключено», \
или отказывается от него в перечне отклонений;
- partly — поставляется только часть объекта (например, только штуцер \
вместо ёмкости);
- unclear — КП об этом объекте ничего не говорит.

Правила:
1. Исключение отдельной детали (насосы, клапаны, трубопроводы, обвязка) — \
не исключение всего объекта.
2. Для excluded и partly дай дословную цитату из КП на языке КП (до 300 \
символов) и раздел S…, откуда она.

Верни ТОЛЬКО JSON:
{"objects": [{"object": "O2", "status": "excluded", \
"quote": "...", "section": "S68"}]}"""


def build_scope_prompt(offer_text: str, objects: str) -> tuple[str, str]:
    """Which TZ objects the offer leaves out entirely."""
    user = f"### Текст КП:\n{offer_text}\n\n### Объекты ТЗ:\n{objects}"
    return _SCOPE_SYSTEM, user
