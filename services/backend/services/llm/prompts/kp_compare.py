"""Prompts of the object-scoped TZ/KP comparison (services/kp_compare).

Each builder returns (system, user). The system prompts do not depend on the
documents, and the user prompts put the parts shared by several calls first,
so the provider's prefix cache can reuse them.
"""

from __future__ import annotations

